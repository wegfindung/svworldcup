function paragraph(text: string) {
  return `<p style="margin:0 0 12px;color:#c6d3ce;">${text}</p>`
}

function buildBody(copy: SwapWindowEmailCopy, shared: SwapWindowSharedCopy) {
  return `
    <div style="display:none;max-height:0;overflow:hidden;opacity:0;">${copy.preheader}</div>
    <p style="margin:0 0 24px;text-align:center;"><img src="{{logo_url}}" alt="The Grand Tournament" width="220" style="display:inline-block;width:220px;max-width:70%;height:auto;"></p>
    <h1 style="margin:0 0 18px;font-size:24px;line-height:1.2;color:#f2efe7;">${copy.title}</h1>
    <p style="margin:0 0 16px;color:#c6d3ce;">${shared.greeting}</p>
    ${copy.paragraphs.map(paragraph).join('')}
    <p style="margin:0 0 20px;"><a href="{{builder_url}}" style="display:inline-block;border-radius:999px;background:#22bd93;color:#07100e;font-weight:700;text-decoration:none;padding:14px 22px;">${shared.cta}</a></p>
    <p style="margin:0 0 16px;color:#c6d3ce;">${shared.helpText} <a href="{{help_url}}" style="color:#22bd93;">${shared.helpLink}</a></p>
    <p style="margin:0;color:#c6d3ce;">${shared.signoff}</p>
  `
}

function toCampaign(seed: SwapWindowEmailSeed): EmailCampaignInput {
  const subjectByLocale = Object.fromEntries(
    Object.entries(seed.copy).map(([locale, copy]) => [locale, copy.subject]),
  ) as Record<SupportedLocale, string>
  const bodyHtmlByLocale = Object.fromEntries(
    Object.entries(seed.copy).map(([locale, copy]) => [
      locale,
      buildBody(copy, sharedCopy[locale as SupportedLocale]),
    ]),
  ) as Record<SupportedLocale, string>

  return {
    kind: 'newsletter',
    status: 'scheduled',
    triggerKey: 'manual',
    subject: subjectByLocale.en,
    bodyHtml: bodyHtmlByLocale.en,
    subjectByLocale,
    bodyHtmlByLocale,
    audienceStatus: 'active',
    audienceLeague: 'all',
    scheduledAt: seed.scheduledAt,
    batchSize: 50,
    requiresMarketingOptIn: true,
  }
}

export const swapWindowEmailCampaigns: EmailCampaignInput[] = swapWindowEmailSeeds.map(toCampaign)
