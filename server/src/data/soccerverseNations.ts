const nationCodes = new Set(soccerverseNations.map((nation) => nation.code))

export function isKnownNationCode(code: string): boolean {
  return nationCodes.has(code)
}

export function getNationName(code: string): string {
  return soccerverseNations.find((nation) => nation.code === code)?.nameEn ?? code
}
